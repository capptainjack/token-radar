// Token Radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol in the snapshot that records no token and is
// a launch of its own: not a wrapped, staked or bridged product, not a
// centralised exchange, not a versioned pool of another protocol. The
// watchlist is the floor (all 40 of its slugs are ranked); the early radar
// adds every other rankable protocol below the floor, by the same function.
// Nothing is hand-picked and no protocol name is ever special-cased.
//
// Implied value follows only from the snapshot's own figures:
//
//   base      = tvl_usd x BASE_MULTIPLE
//   growth    = clamp(change_7d, -50, 200) per cent
//   growthMul = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity  = 0.5 + min(age_days, 1460) / 1460 x 0.7   (age unknown: 365)
//   chainsMul = 1 + 0.04 x min(chains - 1, 10)
//   implied   = max(1, round(base x growthMul x maturity x chainsMul))
//
// Why these four: TVL is the protocol's size today; seven-day growth is its
// direction; age with no token is how long a launch has been pent up; and the
// number of chains is how wide its distribution already is. A protocol that
// is big, growing, old without a token and live on many chains is worth more
// than one that is only big. The farm plan is derived from the same record:
// category, chains, TVL and age decide the action, the capital, the gas and
// the hold, never a hand-written list of names.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

