// Token Radar, model radar-2.
//
// One sealed snapshot in, one ranked board out. Every number below comes
// from the snapshot's own figures: a protocol's TVL, its seven-day TVL
// change, how long it has been listed, and how many chains it runs on.
// No protocol name is ever special-cased. The same function scores every
// row, and the dashboard recomputes it from the same figures.
//
//   implied = round( tvl_usd x 0.30
//                    x (1 + clamp(change_7d, -50, 200) / 100 x 0.6)
//                    x (0.5 + min(age_days, 1460) / 1460 x 0.7)
//                    x (1 + 0.04 x min(max(chains - 1, 0), 10)) )
//
// A protocol is rankable when its snapshot record carries no token at
// all (no market cap, no CoinGecko id, no symbol) and it is a launch of
// its own: not a centralised exchange, not a bridge, not liquid staking,
// liquid restaking or restaked BTC, not a wrapped or staked product of
// a token that already trades, not a versioned pool, and not a product
// of a centralised exchange. The watchlist is the floor, never the
// ceiling: every watchlist slug is ranked, and every other rankable
// protocol is ranked too, whatever its TVL.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_extra: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 200,
  maturity_floor: 0.5,
  maturity_range: 0.7,
  maturity_days: 1460,
  unknown_age_days: 365,
  chain_step: 0.04,
  chain_max_extra: 10,
};

export const MODEL_VERSION = 'radar-2';

